#!/usr/bin/env node
/**
 * Zero-dependency build: reads src/index.js (ES module) and writes
 *   dist/esm/index.js      ES module
 *   dist/cjs/index.js      CommonJS
 *   dist/types/index.d.ts  TypeScript declarations
 */
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(ROOT, "src", "index.js"), "utf8");
const write = (rel, text) => {
  mkdirSync(dirname(join(ROOT, rel)), { recursive: true });
  writeFileSync(join(ROOT, rel), text, "utf8");
};
const must = (s, pattern) => { if (!pattern.test(s)) throw new Error("not found: " + pattern); };

// ── ESM ──────────────────────────────────────────────────────────────────────
write("dist/esm/index.js", src);
write("dist/esm/package.json", JSON.stringify({ type: "module" }) + "\n");

// ── CJS ──────────────────────────────────────────────────────────────────────
const IMPORT = /^import \* as lib from "nodejs-openhab-rest-client";$/m;
const EXPORTS = /^export const \{[^}]*\} = suite;\nexport \{ createTestSuite \};$/m;
must(src, IMPORT); must(src, EXPORTS);
const cjs = `"use strict";\n` + src
  .replace(IMPORT, 'const lib = require("nodejs-openhab-rest-client");')
  .replace(EXPORTS, "module.exports = { ...suite, createTestSuite };");
write("dist/cjs/index.js", cjs);
write("dist/cjs/package.json", JSON.stringify({ type: "commonjs" }) + "\n");

// ── TypeScript declarations ──────────────────────────────────────────────────
function params(list) {
  if (!list.trim()) return "";
  return list.split(",").map(p => {
    const [name, def] = p.split("=").map(s => s.trim());
    return `${name}${def !== undefined ? "?" : ""}: any`;
  }).join(", ");
}
let dts = `// Generated by build.js from src/index.js – do not edit.
// nodejs-openhab-test-suite: same classes and methods as openhab-test-suite (Python).
import type { OpenHABClient } from "nodejs-openhab-rest-client";

`;
const names = [];
for (const m of src.matchAll(/^  class (\w+) \{\n(.*?)^  \}$/gms)) {
  const [, name, body] = m;
  names.push(name);
  const lines = ["  constructor(client: OpenHABClient);"];
  for (const mm of body.matchAll(/^    (static )?(async )?(\w+)\((.*)\) \{$/gm)) {
    const [, isStatic, isAsync, meth, ps] = mm;
    if (meth === "constructor" || meth.startsWith("_")) continue;
    const ret = isStatic ? "boolean" : (meth === "getGroupMembers" || meth === "getLinksForItem") ? "Promise<any[]>"
      : meth === "getThingStatus" || meth === "getRuleStatus" ? "Promise<string | null>" : "Promise<boolean>";
    lines.push(`  ${isStatic ? "static " : ""}${meth}(${params(ps)}): ${ret};`);
  }
  dts += `export declare class ${name} {\n${lines.join("\n")}\n}\n\n`;
}
dts += `/** Builds the tester classes for another instance of the client library. */
export declare function createTestSuite(lib: any): {
${names.map(n => `  ${n}: typeof ${n};`).join("\n")}
};
`;
write("dist/types/index.d.ts", dts);
// per-format copies so that TypeScript ("moduleResolution": "node16"/"nodenext") resolves ESM and CJS
write("dist/esm/index.d.ts", dts);
write("dist/cjs/index.d.ts", dts);
console.log(`✓ dist/esm, dist/cjs, dist/types (${names.join(", ")})`);
